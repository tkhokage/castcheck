import { chromium } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import assert from "node:assert/strict";
const browser = await chromium.launch({channel:"chrome", headless:true, args:["--enable-unsafe-swiftshader"]});
const page = await browser.newPage({viewport:{width:1365,height:900}});
const failures = [];
page.on("pageerror", error => failures.push(error.message));
const base = process.env.PREVIEW_URL || "http://127.0.0.1:3101";
await mkdir("artifacts/agency-district", {recursive:true});
try {
  await page.goto(base + "/agencies");
  const district = page.getByRole("region", {name:"Agency District"});
  await district.getByRole("button", {name:"Explore in 3D"}).waitFor();
  assert.equal(await district.locator("canvas").count(),0);
  await district.getByRole("button", {name:"Explore in 3D"}).click();
  const choice = district.getByRole("button", {name:/^1\./});
  await choice.waitFor();
  await choice.focus();
  await page.keyboard.press("Enter");
  await district.getByRole("link", {name:"View evidence, contact and submission details"}).waitFor();
  await page.waitForTimeout(1800);
  await page.screenshot({path:"artifacts/agency-district/desktop.png",fullPage:true});
  await page.keyboard.press("Escape");
  assert.equal(await district.getByRole("link", {name:"View evidence, contact and submission details"}).count(),0);
  await district.getByRole("button", {name:/^Select /}).first().click();
  await district.getByRole("button", {name:"Reset view"}).click();
  await district.getByRole("link", {name:"View evidence, contact and submission details"}).click();
  await page.waitForURL(/\/agencies\/[^/]+$/);
  await page.goto(base + "/agencies?q=zzzz-no-agency");
  await page.getByText("No agencies match", {exact:true}).waitFor();
  await page.goto(base + "/agencies?location=Dallas");
  await page.getByRole("button",{name:"Explore in 3D"}).click();
  await page.getByRole("button",{name:/^1\./}).click();
  await page.screenshot({path:"artifacts/agency-district/filtered.png",fullPage:true});
  await page.getByRole("combobox",{name:"Filter agencies by representation type"}).selectOption("voice");
  await page.waitForURL(/specialty=voice/);
  await page.getByText("No agencies match",{exact:true}).waitFor();
  assert.equal(await page.getByRole("link",{name:"View evidence, contact and submission details"}).count(),0);
  const mobile = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:"reduce"});
  await mobile.goto(base + "/agencies");
  await mobile.getByRole("button",{name:"Explore in 3D"}).tap();
  await mobile.getByRole("button",{name:/^1\./}).tap();
  await mobile.getByRole("button",{name:/^Select /}).first().waitFor();
  await mobile.getByRole("region",{name:"Agency District"}).screenshot({path:"artifacts/agency-district/mobile.png"});
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await mobile.close();
  const fallback = await browser.newPage();
  await fallback.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function(type,...args) {
      if(String(type).includes("webgl")) return null;
      return original.call(this,type,...args);
    };
  });
  await fallback.goto(base + "/agencies");
  await fallback.getByRole("button",{name:"Explore in 3D"}).click();
  await fallback.getByText("Your browser cannot display 3D.",{exact:false}).waitFor();
  await fallback.getByRole("button",{name:/^1\./}).click();
  await fallback.getByRole("link",{name:"View evidence, contact and submission details"}).waitFor();
  await fallback.screenshot({path:"artifacts/agency-district/fallback.png",fullPage:true});
  await fallback.close();
  assert.deepEqual(failures,[]);
  console.log("PASS: opt-in loading, keyboard selection/Escape, reset, detail navigation, filtered/empty results, mobile/reduced motion, WebGL fallback; no page errors.");
} finally { await browser.close(); }
